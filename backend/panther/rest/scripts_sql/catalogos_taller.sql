CREATE TABLE IF NOT EXISTS cliente_taller (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 documento VARCHAR(20) NOT NULL UNIQUE, nombre VARCHAR(100) NOT NULL,
 telefono VARCHAR(10) NOT NULL, correo VARCHAR(100) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS vehiculo_taller (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, placa CHAR(6) NOT NULL UNIQUE,
 cliente_id INT UNSIGNED NOT NULL, marca VARCHAR(60) NOT NULL, modelo VARCHAR(60) NOT NULL,
 anio SMALLINT UNSIGNED NOT NULL, color VARCHAR(40) NOT NULL DEFAULT '',
 kilometraje INT UNSIGNED NULL,
 FOREIGN KEY (cliente_id) REFERENCES cliente_taller(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS proveedor_taller (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(10) NOT NULL UNIQUE,
 nit VARCHAR(15) NOT NULL UNIQUE, razonSocial VARCHAR(100) NOT NULL,
 direccion VARCHAR(100) NOT NULL, telefono VARCHAR(10) NOT NULL, correo VARCHAR(100) NOT NULL UNIQUE,
 estado ENUM('Activo','Inactivo') NOT NULL DEFAULT 'Activo'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS repuesto_taller (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, referencia VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(100) NOT NULL, precio DECIMAL(12,2) UNSIGNED NOT NULL,
 existencias INT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
